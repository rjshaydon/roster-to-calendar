import assert from 'node:assert/strict';
import {contactSyncHealth,contactSyncWarning} from '../public/static/contact-sync-status.js';
import {facilityContactHealthKey,publishFacilityContactExtract,loadPublishedFacilityContacts} from '../functions/_lib/facility-contact-cache.js';
import {contactOperationalDate} from '../public/static/contact-allocations.js';
const now=new Date(),fresh=now.toISOString(),stale=new Date(now.getTime()-16*60000).toISOString();
assert.equal(contactSyncHealth(fresh,now),'healthy');
assert.equal(contactSyncHealth(stale,now),'delayed');
assert.equal(contactSyncHealth('',now),'unknown');
assert.equal(contactSyncWarning({status:'available',syncHealth:{status:'healthy',lastSuccessAt:fresh}},{live:true}),'','healthy syncing has no interface status text');
assert.equal(contactSyncWarning({status:'not-current'},{live:false}),'','historical or future dates do not create sync alarms');
assert.match(contactSyncWarning({status:'available',syncHealth:{status:'healthy',lastSuccessAt:stale}},{live:true}),/15 minutes/,'the browser also ages cached health during network failures');
assert.match(contactSyncWarning({status:'unavailable',lastSourceDate:'2026-10-05'},{live:true,admin:true}),/worksheet.*2026-10-05.*Power Automate/);
const objects=new Map();let writes=0;
const r2={async get(key){return objects.has(key)?{etag:'fixture',text:async()=>objects.get(key)}:null;},async put(key,value){writes++;objects.set(key,typeof value==='string'?value:new TextDecoder().decode(value));}};
const sourceId='mmc-shift-allocations',sourceDate=contactOperationalDate(now);
const extract={sourceId,sourceDate,contacts:[{area:'Adult Emergency',shift:'AM',role:'Consultant',name:'Test Doctor',phone:'25134',isPopulated:true}]};
await publishFacilityContactExtract(r2,extract);
const healthy=await loadPublishedFacilityContacts(r2,{date:sourceDate,facilityKeys:['MMC'],now});
assert.equal(healthy.syncHealth.status,'healthy');
objects.set(facilityContactHealthKey(sourceId),JSON.stringify({lastSuccessAt:stale,sourceDate}));
const delayed=await loadPublishedFacilityContacts(r2,{date:sourceDate,facilityKeys:['MMC'],now});
assert.equal(delayed.syncHealth.status,'delayed');
assert.notEqual(delayed.revision,healthy.revision,'a stalled flow changes the refresh revision even if contacts are unchanged');
const before=writes;
assert.equal((await publishFacilityContactExtract(r2,extract)).unchanged,true);
assert.equal(writes-before,1,'an unchanged successful check refreshes only the small R2 heartbeat');
const recovered=await loadPublishedFacilityContacts(r2,{date:sourceDate,facilityKeys:['MMC'],now});
assert.equal(recovered.syncHealth.status,'healthy');
assert.equal(recovered.revision,healthy.revision,'recovery removes the warning without replacing contact data');
const after=writes;await publishFacilityContactExtract(r2,extract);assert.equal(writes,after,'duplicate deliveries coalesce heartbeat writes');
console.log('Contact heartbeat, delayed/recovered refresh revisions, silent healthy state and historical-date suppression passed without D1.');
