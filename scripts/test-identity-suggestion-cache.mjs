import assert from 'node:assert/strict';
import { mountIdentityReview } from '../public/static/identity-review-ui.js';
const listeners={};
globalThis.window={addEventListener(){},removeEventListener(){}};
globalThis.document={activeElement:null,visibilityState:'visible',addEventListener(){},removeEventListener(){}};
const section={open:true,addEventListener(type,fn){listeners[type]=fn;},removeEventListener(){}};
const root={isConnected:true,innerHTML:'',closest(){return section;},querySelector(){return {textContent:'',scrollIntoView(){}};}};
const tick=()=>new Promise(resolve=>setImmediate(resolve));
const candidate=(key,left,right)=>({pair_key:key,fingerprint:key,left:{personId:left,displayName:left,sourceType:'ddh'},right:{personId:right,displayName:right,sourceType:'mmc'},evidence:{reason:'Possible name match'}});
let candidates=[candidate('ab','Alfa','Alpha')],calls=[],releaseAudit,releaseFinal,remainingAudits=1;
const gate=new Promise(resolve=>releaseAudit=resolve), finalGate=new Promise(resolve=>releaseFinal=resolve);
const request=async(op,input)=>{calls.push([op,input]);if(op==='candidates')return {candidates:[...candidates],next:''};if(op==='initialize')return {status:'complete',examined:2};if(op==='audit'){if(remainingAudits--){await gate;return {status:'running',runId:'audit1',examined:1,candidates:1};}await finalGate;return {status:'complete',examined:2,candidates:2};}if(op==='person')return {people:[{person_id:input.personId,preferred_display_name:input.personId,status:'active'}],aliases:[],accounts:[],history:[]};if(op==='person-terms')return {terms:[],missingSites:[],missingTerms:[],next:null};if(op==='reject'){candidates=candidates.filter(c=>c.pair_key!==input.pairKey);return {};}throw Error('Unexpected request: '+op);};
const click=(attr,value='')=>root.onclick({target:{closest(){return {dataset:{[attr.replace(/^data-/,'').replace(/-([a-z])/g,(_,c)=>c.toUpperCase())]:value},hasAttribute(name){return name===attr;}};}}});
mountIdentityReview(root,request);
await tick();
assert.equal(calls.filter(([op])=>op==='candidates').length,1,'opening identities preloads just the bounded saved-candidate page');
click('data-id-suggestions');
assert.match(root.innerHTML,/Alfa/,'saved suggestions render synchronously before the audit');
assert.doesNotMatch(root.innerHTML,/Working…/);
await tick();
assert(calls.some(([op])=>op==='audit'));
click('data-id-candidate','0');
await tick();
assert.match(root.innerHTML,/Is this the same person/,'Review works while the audit request is still pending');
assert.equal(calls.filter(([op])=>op==='person').length,2);
candidates.push(candidate('cd','Beta','Betta'));
releaseAudit();
await tick();await tick();
click('data-id-close-person');
assert.match(root.innerHTML,/Betta/,'new findings join the saved suggestions before the audit completes');
releaseFinal();await tick();await tick();
click('data-id-dismiss','0');
await tick();
click('data-id-close-suggestions');
click('data-id-suggestions');
assert.doesNotMatch(root.innerHTML,/<strong>Alfa<\/strong>/,'dismissed matches are removed from the immediate cache');
await tick();
assert.equal(calls.filter(([op])=>op==='audit').length,2,'reopening recently checked suggestions does not launch another audit');
section.open=false;listeners.toggle();root.isConnected=false;
console.log('Saved suggestions appear immediately, stay reviewable during audits, update with new findings and invalidate after dismissal.');
